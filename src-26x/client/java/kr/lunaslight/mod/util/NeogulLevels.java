	public static List<Skill> skillsAt(int track, int lv) {
		List<Skill> out = new ArrayList<>();
		for (Skill k : SKILLS) {
			if (k.track() == track && k.level() == lv) {
				out.add(k);
			}
		}
		return out;
	}

	/** (from, to] 구간에서 새로 배울 수 있는 스킬. */
	public static List<Skill> skillsBetween(int track, int from, int to) {
		List<Skill> out = new ArrayList<>();
		for (Skill k : SKILLS) {
			if (k.track() == track && k.level() > from && k.level() <= to) {
				out.add(k);
			}
		}
		return out;
	}
