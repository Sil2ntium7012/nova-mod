package kr.lunaslight.mod.module;

/**
 * 49-56차: <b>기능과는 별개인</b> 클라이언트 설정 묶음.
 *
 * <p>사용자: "그래픽, UI, 일반 설정은 기능이랑은 별개인 거야. 따로 둬야 하는 거야, 위쪽에 새로 만들어서."
 * (Dawn Client처럼 일반·그래픽 설정이 따로 있고 기능이 따로 있는 구조)
 *
 * <p>{@link ModuleCategory}는 <b>기능 카드 격자</b>를 나누는 값이고, 이쪽은 설정 화면 <b>맨 앞에 붙는
 * 별도 페이지</b>다. 어떤 모듈에 이 값이 붙으면 그 모듈은 기능 격자에서 빠지고 해당 설정 페이지에
 * 평평한 줄로 나온다(카드·켜짐 표시 없이 이름 + 스위치 + 설정 줄).
 *
 * <p>구현상 그대로 Module로 두는 이유: 저장(모듈 id 기준), 믹스인 훅, 버전 잠금이 전부 Module에
 * 붙어 있어서 따로 떼면 같은 것을 두 벌 만들게 된다. <b>보이는 방식만</b> 다르다.
 *
 * <p><b>49-61차 - 여기에 뭘 올릴지의 규칙</b>(사용자: "기존 기능에 있던 것들을 갑자기 그래픽 쪽으로
 * 다 옮기면 안 되지, 일반 설정에 있는 그래픽이랑 기능에 그래픽은 다른 거라니까"):
 *
 * <ul>
 *   <li><b>설정</b>은 클라이언트가 어떻게 동작할지를 정하는 것 - 켜고 끄는 "기능"이 아니다.
 *       (예: 글꼴, 채팅 숨기기 규칙, 알림 끄기)</li>
 *   <li><b>기능</b>은 있으면 늘어나고 없으면 그만인 것 - 화면을 만지더라도 기능은 기능이다.
 *       밝기·색보정·시야 고정·입자 끄기·엔티티 줄이기는 전부 여기다(49-56차에 [그래픽]으로
 *       옮겼다가 49-61차에 전부 되돌렸다).</li>
 * </ul>
 *
 * <p>그래서 <b>이미 기능 격자에 있던 것을 설정 페이지로 옮기는 건 하지 않는다</b>. 설정 페이지는
 * "기능으로는 없던 클라이언트 자체 옵션"을 새로 만들어 채운다. {@code GRAPHICS}는 지금 그런 항목이
 * 하나도 없어서 <b>비어 있고</b>, 비어 있는 페이지는 탭 줄에 아예 안 뜬다(LunaClientScreen.pages()).
 */
public enum SettingsPage {
	GENERAL("일반"),
	UI("UI"),
	GRAPHICS("그래픽"),
	/** 49-89차(8-8): 단축키 - 내 단축키(하나씩 추가) + 마인크래프트 보조 키. */
	KEYS("키바인드");   // 49-195차(사용자: "키를 키바인드로 이름 변경")

	private final String displayName;

	SettingsPage(String displayName) {
		this.displayName = displayName;
	}

	public String getDisplayName() {
		return displayName;
	}
}
